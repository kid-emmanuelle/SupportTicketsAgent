-- créer la base
CREATE DATABASE IF NOT EXISTS PROJECT_DB;

-- créer les schémas
CREATE SCHEMA IF NOT EXISTS PROJECT_DB.APP;
CREATE SCHEMA IF NOT EXISTS PROJECT_DB.CURATED;
CREATE SCHEMA IF NOT EXISTS PROJECT_DB.EVAL;
CREATE SCHEMA IF NOT EXISTS PROJECT_DB.RAW;
CREATE SCHEMA IF NOT EXISTS PROJECT_DB.SERVICES;

-- créer la table SUPPORT_TICKETS dans le schéma RAW
CREATE TABLE IF NOT EXISTS PROJECT_DB.RAW.SUPPORT_TICKETS (
    SUBJECT VARCHAR(16777216),
    BODY VARCHAR(16777216),
    ANSWER VARCHAR(16777216),
    TYPE VARCHAR(16777216),
    QUEUE VARCHAR(16777216),
    PRIORITY VARCHAR(16777216),
    LANGUAGE VARCHAR(16777216),
    VERSION NUMBER(38,0),
    TAG_1 VARCHAR(16777216),
    TAG_2 VARCHAR(16777216),
    TAG_3 VARCHAR(16777216),
    TAG_4 VARCHAR(16777216),
    TAG_5 VARCHAR(16777216),
    TAG_6 VARCHAR(16777216),
    TAG_7 VARCHAR(16777216),
    TAG_8 VARCHAR(16777216)
);
